import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { generatePaper } from "../src/engine.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const bankPath = path.join(__dirname, "..", "src", "questions.json");
const outPath = path.join(__dirname, "..", "sample-paper.md");

const bank = JSON.parse(fs.readFileSync(bankPath, "utf8"));
const config = {
  total: 20,
  mixes: {
    difficulty: { Easy: 30, Medium: 50, Hard: 20 },
    topic: { Biology: 40, Chemistry: 30, Physics: 30 },
    type: { MCQ: 40, "Short Answer": 40, "Long Answer": 20 },
  },
};

const result = generatePaper(bank, config, { seed: 42 });
const lines = [
  "# Sample Science Question Paper",
  "",
  "**Maximum marks:** 20",
  "**Engine seed:** 42",
  `**Exact total:** ${result.exactTotal}`,
  "",
];

if (result.conflicts.length) {
  lines.push("**Feasibility notes:**");
  for (const c of result.conflicts) lines.push(`- ${c}`);
  lines.push("");
}

let n = 1;
for (const q of result.paper) {
  lines.push(
    `${n}. **[${q.marks} mark${q.marks === 1 ? "" : "s"} · ${q.difficulty} · ${q.type} · ${q.topic}]** ${q.prompt}`,
  );
  if (q.options) {
    const labels = ["A", "B", "C", "D"];
    q.options.forEach((o, i) => lines.push(`   - ${labels[i]}. ${o}`));
  }
  lines.push("");
  n += 1;
}

const total = result.paper.reduce((s, q) => s + q.marks, 0);
lines.push(`**Total: ${total} marks**`);
lines.push("");
lines.push("<!-- Generated by scripts/generate-sample-paper.mjs -->");

fs.writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`Wrote ${outPath} (${result.paper.length} questions, ${total} marks, exact=${result.exactTotal})`);
